-- Применяется внутри выбранной схемы (search_path).
CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL CHECK (btrim(name) <> ''),
 registered_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE customers (
 user_id bigint PRIMARY KEY REFERENCES users(id)
);
CREATE TABLE freelancers (
 user_id bigint PRIMARY KEY REFERENCES users(id),
 specialization text NOT NULL CHECK (btrim(specialization) <> ''),
 hourly_rate numeric(12,2) NOT NULL CHECK (hourly_rate > 0)
);
CREATE TABLE projects (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id bigint NOT NULL REFERENCES customers(user_id),
 title text NOT NULL CHECK (btrim(title) <> ''),
 description text NOT NULL DEFAULT '',
 budget numeric(14,2) NOT NULL CHECK (budget > 0),
 status text NOT NULL DEFAULT 'открыт' CHECK (status IN ('открыт','в работе','завершен')),
 created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
 completed_at timestamp,
 CHECK ((status = 'завершен') = (completed_at IS NOT NULL)),
 CHECK (completed_at IS NULL OR completed_at >= created_at)
);
CREATE TABLE bids (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id bigint NOT NULL REFERENCES projects(id),
 freelancer_id bigint NOT NULL REFERENCES freelancers(user_id),
 amount numeric(14,2) NOT NULL CHECK (amount > 0),
 proposed_completion_date date NOT NULL,
 status text NOT NULL DEFAULT 'подана' CHECK (status IN ('подана','принята','отклонена')),
 submitted_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
 accepted_at timestamp,
 rejected_at timestamp,
 UNIQUE (project_id, freelancer_id),
 CHECK (proposed_completion_date >= submitted_at::date),
 CHECK ((status = 'подана' AND accepted_at IS NULL AND rejected_at IS NULL)
     OR (status = 'принята' AND accepted_at IS NOT NULL AND rejected_at IS NULL)
     OR (status = 'отклонена' AND rejected_at IS NOT NULL AND accepted_at IS NULL)),
 CHECK (accepted_at IS NULL OR accepted_at >= submitted_at),
 CHECK (rejected_at IS NULL OR rejected_at >= submitted_at)
);
CREATE UNIQUE INDEX one_accepted_bid_per_project ON bids(project_id) WHERE status = 'принята';
CREATE INDEX bids_freelancer_date ON bids(freelancer_id, submitted_at);
CREATE TABLE reviews (
 project_id bigint PRIMARY KEY REFERENCES projects(id),
 rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
 comment text NOT NULL,
 created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
